create or replace function public.get_employee_json(p_id bigint)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
    select jsonb_build_object(
        'id', e.id,
        'name', e.name,
        'job_number', coalesce(e.job_number, ''),
        'national_id', coalesce(e.national_id, ''),
        'job_title', coalesce(e.job_title, ''),
        'initial_carried_forward', e.initial_carried_forward,
        'over_45', e.over_45,
        'is_frozen', e.is_frozen,
        'include_in_print', e.include_in_print,
        'is_unpaid_leave', e.is_unpaid_leave,
        'is_archived', e.is_archived,
        'hire_date', coalesce(e.hire_date, ''),
        'hire_date_current_year', e.hire_date_current_year,
        'ceiled_cumulative_balance', e.ceiled_cumulative_balance,
        'carryover_ceiled_at_year', e.carryover_ceiled_at_year,
        'years_data', coalesce((
            select jsonb_object_agg(ey.year,
                       jsonb_build_object('added', ey.added, 'deducted', ey.deducted))
            from public.employee_years ey where ey.employee_id = e.id
        ), '{}'::jsonb),
        'deductions_history', coalesce((
            select jsonb_agg(jsonb_build_object(
                       'id', d.id, 'year', d.year, 'start', d.start_date,
                       'end', d.end_date, 'days', d.days, 'note', d.note,
                       'createdBy', d.created_by, 'createdAt', d.created_at,
                       'deductionSource', d.deduction_source
                   ) order by d.id)
            from public.deductions d where d.employee_id = e.id
        ), '[]'::jsonb),
        'createdAt', e.created_at
    )
    from public.employees e where e.id = p_id;
$$;

-- Weekday day-count, faithful to backend/src/utils/days.js.
-- Postgres dow: 0=Sun .. 6=Sat (same mapping as JS getDay()).
-- Unified weekend rule for ALL employees: Friday(5) + Saturday(6) only.
drop function if exists public.calculate_deduction_days(text, text, numeric);
drop function if exists public.calculate_deduction_days(text, text, numeric, boolean);
drop function if exists public.calculate_deduction_days(date, date, numeric);
drop function if exists public.calculate_deduction_days(date, date, integer);
drop function if exists public.calculate_deduction_days(timestamp, timestamp, numeric);
create or replace function public.calculate_deduction_days(
    start_date date,
    end_date   date,
    custom_holidays numeric default 0
) returns numeric
language plpgsql
immutable
as $$
declare
    cur date; cnt int := 0; wd int;
begin
    if start_date is null or end_date is null then
        return 0;
    end if;
    if end_date < start_date then return 0; end if;

    cur := start_date;
    while cur <= end_date loop
        wd := extract(dow from cur)::int;
        if wd != 5 and wd != 6 then cnt := cnt + 1; end if;
        cur := cur + 1;
    end loop;

    return greatest(0, cnt - coalesce(custom_holidays, 0));
end;
$$;

