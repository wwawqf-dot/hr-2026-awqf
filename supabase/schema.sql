create or replace function public.employee_net_balance(p_employee_id bigint)
returns numeric
language plpgsql
stable
security definer
set search_path = public
as $$
declare
    emp        public.employees%rowtype;
    v_cur_year text;
    v_balance  numeric;
begin
    select * into emp from public.employees where id = p_employee_id;
    if not found then return 0; end if;

    v_cur_year := to_char((now() at time zone 'Africa/Tripoli')::date, 'YYYY');

    select coalesce(emp.initial_carried_forward, 0)
         + coalesce(sum(
               case when ey.year = v_cur_year and emp.is_unpaid_leave
                    then 0 else coalesce(ey.added, 0) end
               - coalesce(ey.deducted, 0)), 0)
      into v_balance
      from public.employee_years ey
     where ey.employee_id = p_employee_id;

    return round(v_balance, 2);
end;
$$;


-- ---------------------------------------------------------------------
-- 2. (8/16) COUNTER RECONCILIATION — employee_years.deducted is, by
--    design, exactly the sum of that employee-year's deduction rows.
--    Every writer maintains that invariant; only sync_employees could
--    break it. Make the invariant enforceable instead of assumed.
-- ---------------------------------------------------------------------
create or replace function public.reconcile_counters(p_employee_ids bigint[] default null)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
    v_fixed int := 0;
begin
    -- A deduction whose (employee, year) has no counter row at all would
    -- otherwise be invisible to the recompute below. The allocation is
    -- filled in the same way add_year() would have, so the restored row
    -- neither invents nor withholds entitlement.
    insert into public.employee_years (employee_id, year, added, deducted)
    select distinct d.employee_id, d.year,
           public.year_allocation(d.year, e.over_45, e.hire_date_current_year,
                                  coalesce(y.default_days, 30)), 0
      from public.deductions d
      join public.employees e on e.id = d.employee_id
      join public.years     y on y.year = d.year
     where (p_employee_ids is null or d.employee_id = any(p_employee_ids))
       and d.year ~ '^\d{4}$'
       and not exists (
           select 1 from public.employee_years ey
            where ey.employee_id = d.employee_id and ey.year = d.year)
    on conflict (employee_id, year) do nothing;

    with drift as (
        select ey.id,
               coalesce((select sum(d.days) from public.deductions d
                          where d.employee_id = ey.employee_id and d.year = ey.year), 0) as real_deducted
          from public.employee_years ey
         where (p_employee_ids is null or ey.employee_id = any(p_employee_ids))
    ),
    fixed as (
        update public.employee_years ey
           set deducted = drift.real_deducted
          from drift
         where ey.id = drift.id
           and coalesce(ey.deducted, 0) is distinct from drift.real_deducted
        returning 1
    )
    select count(*) into v_fixed from fixed;

    return v_fixed;
end;
$$;

-- Admin-facing wrapper: audit the whole database and repair any drift.
-- Repair engine for the stored grant itself. employee_years.added is
-- written once, when the year is opened or the employee is created; the
-- employee's track (over_45) and hire date can change afterwards, and an
-- employee restored from the archive may have no row for the year at all.
-- This re-derives both from what the employee IS today, for the current
-- financial year and any year opened ahead of it. Closed and archived
-- years are never touched.
create or replace function public.reconcile_allocations(p_employee_ids bigint[] default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_cur_year text := to_char((now() at time zone 'Africa/Tripoli')::date, 'YYYY');
    v_created  int  := 0;
    v_fixed    int  := 0;
    v_blocked  jsonb;
begin
    -- Grant the year to an active employee who has no row for it — the
    -- archived-then-restored case add_year() could never have seen.
    insert into public.employee_years (employee_id, year, added, deducted)
    select e.id, y.year,
           public.year_allocation(y.year, e.over_45, e.hire_date_current_year,
                                  coalesce(y.default_days, 30)), 0
      from public.employees e
      cross join public.years y
     where e.is_archived = false
       and coalesce(y.is_archived, false) = false
       and y.year ~ '^\d{4}$'
       and y.year >= v_cur_year
       and (p_employee_ids is null or e.id = any(p_employee_ids))
       and not exists (select 1 from public.employee_years ey
                        where ey.employee_id = e.id and ey.year = y.year)
    on conflict (employee_id, year) do nothing;
    get diagnostics v_created = row_count;

    with cand as (
        select ey.id, ey.employee_id, ey.year,
               ey.added    as stored,
               ey.deducted as deducted,
               public.year_allocation(ey.year, e.over_45, e.hire_date_current_year,
                                      coalesce(y.default_days, 30)) as owed,
               e.is_unpaid_leave
          from public.employee_years ey
          join public.employees e on e.id = ey.employee_id
          join public.years     y on y.year = ey.year
         where e.is_archived = false
           and coalesce(y.is_archived, false) = false
           and ey.year ~ '^\d{4}$'
           and ey.year >= v_cur_year
           and (p_employee_ids is null or ey.employee_id = any(p_employee_ids))
    ),
    changed as (
        select *, case when is_unpaid_leave and year = v_cur_year
                       then 0 else owed - stored end as delta
          from cand
         where owed is distinct from stored
    ),
    solvent as (
        select c.employee_id
          from changed c
         group by c.employee_id
        having public.employee_net_balance(c.employee_id) + sum(c.delta) >= 0
    ),
    applied as (
        update public.employee_years ey
           set added = c.owed
          from changed c
          join solvent s on s.employee_id = c.employee_id
         where ey.id = c.id
        returning 1
    )
    select count(*) into v_fixed from applied;

    -- Whatever still mismatches is, by construction, a row the guard
    -- refused. Report the resulting net so the reason is visible.
    select coalesce(jsonb_agg(jsonb_build_object(
               'employee',   e.name,
               'job_number', coalesce(e.job_number, ''),
               'year',       ey.year,
               'stored',     ey.added,
               'correct',    v.owed,
               'deducted',   ey.deducted,
               'net',        public.employee_net_balance(e.id) + (v.owed - ey.added)
           ) order by e.name), '[]'::jsonb)
      into v_blocked
      from public.employee_years ey
      join public.employees e on e.id = ey.employee_id
      join public.years     y on y.year = ey.year
      cross join lateral (
           select public.year_allocation(ey.year, e.over_45, e.hire_date_current_year,
                                         coalesce(y.default_days, 30)) as owed) v
     where e.is_archived = false
       and coalesce(y.is_archived, false) = false
       and ey.year ~ '^\d{4}$'
       and ey.year >= v_cur_year
       and (p_employee_ids is null or ey.employee_id = any(p_employee_ids))
       and v.owed is distinct from ey.added;

    return jsonb_build_object('created', v_created,
                              'fixed',   v_fixed,
                              'blocked', v_blocked);
end;
$$;


