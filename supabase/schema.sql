                                        ) order by d.id)
                                 from public.deductions d
                                 where d.employee_id = e.id and d.year = p_year
                             ), '[]'::jsonb)
                   ) order by e.id)
            from public.employees e
        ), '[]'::jsonb)
    );
$$;

-- Archive (freeze) one year into its own isolated box. Admin only.
-- Never deletes or modifies live rows — safe to re-run.
create or replace function public.finalize_year(p_year text, p_frozen_by text default '')
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
