-- ---------------------------------------------------------------------
-- 9. YEAR ARCHIVES — every financial year frozen in its own sealed box
-- ---------------------------------------------------------------------
-- When a new financial year is opened, the previous year is mirrored
-- into `year_archives`: a self-contained snapshot (employees that
-- existed + their that-year balances + that year's deduction register).
-- The live tables are never altered — this is a separate, isolated copy
-- so 2026's data stays entirely apart from 2027's, and the deduction
-- register keeps flowing into the new year via get_employee_json()'s
-- deductions_history for continuity and audit.
create table if not exists public.year_archives (
    id           bigint generated by default as identity primary key,
    year         text not null unique,
    frozen_at    timestamptz not null default now(),
    frozen_by    text default '',
    snapshot     jsonb not null
);

create or replace function public.build_year_archive_snapshot(p_year text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
    select jsonb_build_object(
        'year', p_year,
        'frozenAt', now(),
        'employees', coalesce((
            select jsonb_agg(jsonb_build_object(
                       'id', e.id,
                       'name', e.name,
                       'job_number', coalesce(e.job_number, ''),
                       'national_id', coalesce(e.national_id, ''),
                       'job_title', coalesce(e.job_title, ''),
                       'over_45', e.over_45,
                       'is_frozen', e.is_frozen,
                       'include_in_print', e.include_in_print,
                       'is_unpaid_leave', e.is_unpaid_leave,
                       'hire_date', coalesce(e.hire_date, ''),
                       'years_data', coalesce((
                           select jsonb_object_agg(ey.year,
                                       jsonb_build_object('added', ey.added, 'deducted', ey.deducted))
                           from public.employee_years ey
                           where ey.employee_id = e.id
                       ), '{}'::jsonb),
                       'deductions_history', coalesce((
                                 select jsonb_agg(jsonb_build_object(
                                            'id', d.id, 'year', d.year, 'start', d.start_date,
                                            'end', d.end_date, 'days', d.days, 'note', d.note,
